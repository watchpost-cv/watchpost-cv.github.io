const fs=require('fs');
const assert=(ok,msg)=>{if(!ok)throw new Error(msg)};
const html=fs.readFileSync('public/redirect.html','utf8');
const js=fs.readFileSync('public/assets/js/script.js','utf8');
assert(html.includes('data-watchpost-launcher'),'generated redirect page missing launcher root');
assert(html.includes('data-main-default-port="7334"'),'Watchpost default port missing');
assert(html.includes('data-agent-default-port="7335"'),'Watchpost Agent default port missing');
assert(js.includes("?'agent':'invalid'"),'agent query mode missing');
assert(js.includes("mode==='agent'"),'agent redirect branch missing');
assert(js.includes("mainKey='watchpost-local-port'"),'main port storage missing');
assert(js.includes("agentKey='watchpost-agent-local-port'"),'agent port storage missing');
assert(js.includes('window.location.replace(`http://localhost:${port}/`)'),'localhost redirect missing');
assert(!js.includes("params.has('port')")&&!js.includes("params.has('portno')"),'query port mutation unexpectedly supported');
assert(!html.includes('@content')&&!html.includes('@input('),'generated page contains unresolved Nift syntax');
console.log('watchpost redirect launcher check: ok');
